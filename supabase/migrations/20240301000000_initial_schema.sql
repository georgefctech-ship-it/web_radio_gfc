-- 1. Habilitar Extensões (se não estiverem habilitadas)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Tabela de Estações (Gêneros)
CREATE TABLE stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    genre TEXT[] DEFAULT '{}',
    cover_url TEXT,
    stream_url TEXT NOT NULL,
    listener_count BIGINT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabela de Músicas (Playlist)
CREATE TABLE songs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id BIGINT REFERENCES stations(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    artist TEXT NOT NULL,
    album TEXT,
    duration INTEGER, -- duração em segundos
    cover_url TEXT,
    audio_url TEXT NOT NULL, -- URL do arquivo no Storage
    created_at TIMESTAMPTZ DEFAULT NOW(),
    order_index INTEGER DEFAULT 0 -- para ordenar a playlist
);

-- 4. Tabela para o Estado Atual da Música
CREATE TABLE current_song (
    id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1), -- Garante que só tenha uma linha
    station_id BIGINT REFERENCES stations(id) ON DELETE CASCADE,
    song_id BIGINT REFERENCES songs(id) ON DELETE SET NULL,
    progress INTEGER DEFAULT 0, -- progresso em segundos
    is_playing BOOLEAN DEFAULT TRUE,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Tabela de Chat
CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    user_name TEXT, -- Nome do usuário (anônimo ou do auth)
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Tabela de Presença (Ouvintes Ativos)
-- Não precisa de uma tabela SQL, será gerenciado pelo Realtime Presence.

-- 7. Configurar Segurança em Nível de Linha (RLS)
ALTER TABLE stations ENABLE ROW LEVEL SECURITY;
ALTER TABLE songs ENABLE ROW LEVEL SECURITY;
ALTER TABLE current_song ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

-- Políticas: Todos podem LER, apenas usuários autenticados (ADMIN) podem MODIFICAR
CREATE POLICY "Todos podem ver estações" ON stations FOR SELECT USING (true);
CREATE POLICY "Apenas admins podem modificar estações" ON stations FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Todos podem ver músicas" ON songs FOR SELECT USING (true);
CREATE POLICY "Apenas admins podem modificar músicas" ON songs FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Todos podem ver música atual" ON current_song FOR SELECT USING (true);
CREATE POLICY "Apenas admins podem modificar música atual" ON current_song FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Todos podem ver mensagens" ON messages FOR SELECT USING (true);
CREATE POLICY "Usuários logados ou anônimos podem inserir mensagens" ON messages FOR INSERT WITH CHECK (true);

